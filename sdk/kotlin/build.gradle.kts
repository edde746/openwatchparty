// The integration tests (src/jvmTest) run a real relay built from relay/ with Go.
val buildRelay = tasks.register<Exec>("buildRelay") {
    val binary = layout.buildDirectory.file("relay/owp-relay")
    workingDir(repoRoot.dir("relay"))
    inputs.dir(repoRoot.dir("relay")).withPropertyName("relaySources")
    outputs.file(binary)
    commandLine("go", "build", "-o", binary.get().asFile.absolutePath, "./cmd/owp-relay")
}

tasks.named<Test>("jvmTest") {
    // A relay rebuilt from changed sources runs the integration tests again.
    inputs.files(buildRelay).withPropertyName("relay")
    systemProperty("owp.relay", layout.buildDirectory.file("relay/owp-relay").get().asFile.absolutePath)
}

