gradle.taskGraph.whenReady {
    val publishing = allTasks.filterIsInstance<AbstractPublishToMaven>()
    // A release without the Android artifact would look complete, so no publishing runs without the Android target.
    if (publishing.isNotEmpty() && !androidEnabled) {
        throw GradleException(
            "Publishing needs the Android target, which is off. Give the build an Android SDK (local.properties " +
                "sdk.dir or ANDROID_HOME) and pass -Popenwatchparty.android=true.",
        )
    }
    // Maven Central takes only signed files; a publication to the local Maven repository may go unsigned.
    signing.isRequired = publishing.any { it is PublishToMavenRepository && it.repository.name == "mavenCentral" }
}
