/**
 * Writes `conformance/vectors/` and the root `relays.json` into one Kotlin source of commonTest, so every target
 * (JVM, Android host, Kotlin/Native) reads the same bytes without a file API. Each string constant holds at most
 * 16000 characters, every character outside printable ASCII as a \u escape (JVM constants are limited to 64 KiB).
 */
abstract class GenerateTestData : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val vectors: DirectoryProperty

    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val publicRelays: RegularFileProperty

    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @TaskAction
    fun generate() {
        fun literal(text: String): String = text.chunked(16000).joinToString(" +\n        ") { chunk ->
            buildString {
                append('"')
                for (c in chunk) {
                    when {
                        c == '"' -> append("\\\"")
                        c == '\\' -> append("\\\\")
                        c == '$' -> append("\\$")
                        c in ' '..'~' -> append(c)
                        else -> append("\\u").append(c.code.toString(16).padStart(4, '0'))
                    }
                }
                append('"')
            }
        }
        val tables = vectors.get().asFile.listFiles { f -> f.isFile && f.name.endsWith(".json") }!!.sortedBy { it.name }
        val source = buildString {
            appendLine("// Generated by the generateTestData task from conformance/vectors and relays.json.")
            appendLine("package party.openwatch")
            appendLine()
            appendLine("internal object TestData {")
            appendLine("    /** Every file of conformance/vectors, by file name. */")
            appendLine("    val vectors: Map<String, String> = mapOf(")
            for (file in tables) {
                appendLine("        \"${file.name}\" to ${literal(file.readText())},")
            }
            appendLine("    )")
            appendLine()
            appendLine("    /** relays.json at the repository root, the canonical public relay list. */")
            appendLine("    val publicRelays: String = ${literal(publicRelays.get().asFile.readText())}")
            appendLine("}")
        }
        val dir = output.get().asFile.resolve("party/openwatch")
        dir.mkdirs()
        dir.resolve("TestData.kt").writeText(source)
    }
}

tasks.register<GenerateTestData>("generateTestData") {
    vectors.set(repoRoot.dir("conformance/vectors"))
    publicRelays.set(repoRoot.file("relays.json"))
    output.set(layout.buildDirectory.dir("generated/testData"))
}

