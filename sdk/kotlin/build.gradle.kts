// The Android target needs an Android SDK. It is on when `-Popenwatchparty.android=true`, off when `=false`, and
// otherwise on exactly when an SDK location is known (local.properties `sdk.dir`, ANDROID_HOME or ANDROID_SDK_ROOT).
val androidEnabled: Boolean = providers.gradleProperty("openwatchparty.android").map { it.toBoolean() }.getOrElse(
    run {
        val local = rootDir.resolve("local.properties")
        val sdkDir = if (local.isFile) Properties().apply { local.reader().use(::load) }.getProperty("sdk.dir") else null
        sdkDir != null || System.getenv("ANDROID_HOME") != null || System.getenv("ANDROID_SDK_ROOT") != null
    },
)
if (androidEnabled) apply(plugin = libs.plugins.android.kmp.library.get().pluginId)

